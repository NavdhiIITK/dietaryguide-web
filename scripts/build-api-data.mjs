#!/usr/bin/env node
/**
 * Strips TypeScript from src/data/{recipes,products,store-products}.ts and
 * writes plain-JS copies into shared/_data/, for the recipe/product SSR
 * functions (api/recipe.js, api/product.js, api/sitemap.js) to import.
 *
 * Why this exists: those functions originally imported the .ts files
 * directly (`../src/data/recipes.ts`). That worked in every local check —
 * `npm run build`, and even a plain `node -e "import('./src/data/recipes.ts')"`,
 * because Node 22.6+ strips TS types natively. But the deployed Vercel
 * function crashed with `Cannot find module '/var/task/src/data/recipes.ts'`
 * (ERR_MODULE_NOT_FOUND) — confirmed by making the import failure catchable
 * and reading the real error back from the live preview, instead of Vercel's
 * generic FUNCTION_INVOCATION_FAILED. Files under src/ aren't traced into the
 * serverless function bundle at all (this Vite project's src/ tree is treated
 * as frontend-only), regardless of extension or the runtime's Node version.
 * shared/*.mjs, by contrast, IS traced correctly — api/blog.js already
 * imports shared/blog-seo.mjs successfully on the same deployment. So rather
 * than depend on undocumented Vercel bundling behavior for src/, or on the
 * function runtime happening to support TS natively, this generates a plain
 * .mjs copy in the one location already proven to work, using esbuild (a
 * mature, already-installed dependency of Vite) instead of a Node version
 * feature.
 *
 * src/data/*.ts remain the single edited-by-hand source of truth — this
 * output is regenerated by the "prebuild" script on every build and is not
 * committed to git.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { transform } from 'esbuild';

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const OUT_DIR = path.join(ROOT, 'shared', '_data');

const FILES = ['recipes', 'products', 'store-products'];

mkdirSync(OUT_DIR, { recursive: true });

for (const name of FILES) {
  const srcPath = path.join(ROOT, 'src', 'data', `${name}.ts`);
  const outPath = path.join(OUT_DIR, `${name}.mjs`);

  const source = readFileSync(srcPath, 'utf-8');
  const result = await transform(source, { loader: 'ts', format: 'esm', target: 'node18' });

  writeFileSync(outPath, result.code, 'utf-8');
  console.log(`build-api-data: wrote ${path.relative(ROOT, outPath)}`);
}
